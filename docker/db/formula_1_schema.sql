-- shared relational schema for formula 1 ingestion, prediction, and retention analysis.
-- identifiers use text to preserve source-system ids and leading zeros.

create schema if not exists formula_one;
set search_path to formula_one;

create table if not exists season (
    season_year smallint primary key check (season_year between 1950 and 2200),
    is_complete boolean not null default false
);

create table if not exists location (
    location_id bigint generated by default as identity primary key,
    source_name text,
    city text,
    country text,
    latitude numeric(9, 6) check (latitude between -90 and 90),
    longitude numeric(9, 6) check (longitude between -180 and 180),
    elevation_m numeric(8, 2),
    unique (source_name, city, country)
);

create table if not exists circuit (
    circuit_id text primary key,
    circuit_name text not null,
    circuit_type text,
    direction text,
    location_id bigint references location (location_id),
    length_km numeric(8, 3) check (length_km is null or length_km > 0),
    turns smallint check (turns is null or turns >= 0),
    source_url text
);

create table if not exists constructor (
    constructor_id text primary key,
    constructor_name text not null
);

create table if not exists driver (
    driver_id text primary key,
    driver_name text not null,
    nationality text,
    continent text,
    date_of_birth date
);

create table if not exists race (
    race_id text primary key,
    season_year smallint not null references season (season_year),
    round smallint check (round is null or round > 0),
    circuit_id text references circuit (circuit_id),
    race_name text,
    race_date date,
    source_url text,
    unique (season_year, round)
);

create table if not exists race_result (
    race_id text not null references race (race_id),
    driver_id text not null references driver (driver_id),
    constructor_id text references constructor (constructor_id),
    finish_position smallint check (finish_position is null or finish_position > 0),
    result_status text,
    points numeric(8, 3) not null default 0,
    laps_completed integer check (laps_completed is null or laps_completed >= 0),
    starting_position smallint check (starting_position is null or starting_position > 0),
    fastest_lap_seconds numeric(10, 3) check (
        fastest_lap_seconds is null or fastest_lap_seconds > 0
    ),
    fastest_lap_number integer check (
        fastest_lap_number is null or fastest_lap_number > 0
    ),
    primary key (race_id, driver_id)
);

create table if not exists practice_result (
    race_id text not null references race (race_id),
    driver_id text not null references driver (driver_id),
    constructor_id text references constructor (constructor_id),
    session_type text not null,
    best_lap_seconds numeric(10, 3) check (
        best_lap_seconds is null or best_lap_seconds > 0
    ),
    lap_count integer check (lap_count is null or lap_count >= 0),
    session_position smallint check (
        session_position is null or session_position > 0
    ),
    primary key (race_id, driver_id, session_type)
);

create table if not exists qualifying_result (
    race_id text not null references race (race_id),
    driver_id text not null references driver (driver_id),
    constructor_id text references constructor (constructor_id),
    q1_seconds numeric(10, 3) check (q1_seconds is null or q1_seconds > 0),
    q2_seconds numeric(10, 3) check (q2_seconds is null or q2_seconds > 0),
    q3_seconds numeric(10, 3) check (q3_seconds is null or q3_seconds > 0),
    qualifying_position smallint check (
        qualifying_position is null or qualifying_position > 0
    ),
    qualifying_laps integer check (
        qualifying_laps is null or qualifying_laps >= 0
    ),
    primary key (race_id, driver_id)
);

create table if not exists pit_stop (
    race_id text not null references race (race_id),
    driver_id text not null references driver (driver_id),
    constructor_id text references constructor (constructor_id),
    stop_number smallint not null check (stop_number > 0),
    stop_lap integer check (stop_lap is null or stop_lap > 0),
    pit_duration_seconds numeric(10, 3) check (
        pit_duration_seconds is null or pit_duration_seconds > 0
    ),
    primary key (race_id, driver_id, stop_number)
);

create table if not exists weather_summary (
    race_id text not null references race (race_id),
    session_type text not null,
    air_temp_mean numeric(8, 3),
    air_temp_min numeric(8, 3),
    air_temp_max numeric(8, 3),
    air_temp_std numeric(8, 3),
    track_temp_mean numeric(8, 3),
    track_temp_min numeric(8, 3),
    track_temp_max numeric(8, 3),
    track_temp_std numeric(8, 3),
    wind_speed_mean numeric(8, 3),
    wind_speed_min numeric(8, 3),
    wind_speed_max numeric(8, 3),
    wind_speed_std numeric(8, 3),
    humidity_mean numeric(8, 3),
    humidity_min numeric(8, 3),
    humidity_max numeric(8, 3),
    humidity_std numeric(8, 3),
    pressure_mean numeric(10, 3),
    pressure_min numeric(10, 3),
    pressure_max numeric(10, 3),
    pressure_std numeric(10, 3),
    rainfall_any boolean,
    rainfall_mean numeric(8, 3),
    primary key (race_id, session_type)
);

create table if not exists race_control_summary (
    race_id text not null references race (race_id),
    yellow_flag_probability numeric(6, 5) check (
        yellow_flag_probability is null or yellow_flag_probability between 0 and 1
    ),
    double_yellow_probability numeric(6, 5) check (
        double_yellow_probability is null or double_yellow_probability between 0 and 1
    ),
    red_flag_probability numeric(6, 5) check (
        red_flag_probability is null or red_flag_probability between 0 and 1
    ),
    safety_car_probability numeric(6, 5) check (
        safety_car_probability is null or safety_car_probability between 0 and 1
    ),
    vsc_probability numeric(6, 5) check (
        vsc_probability is null or vsc_probability between 0 and 1
    ),
    avg_yellow_count numeric(8, 3),
    avg_double_yellow_count numeric(8, 3),
    avg_red_count numeric(8, 3),
    avg_safety_car_deployments numeric(8, 3),
    avg_vsc_deployments numeric(8, 3),
    avg_safety_car_laps numeric(8, 3),
    avg_vsc_laps numeric(8, 3),
    primary key (race_id)
);

create table if not exists driver_session_tire_performance (
    race_id text not null references race (race_id),
    driver_id text not null references driver (driver_id),
    session_type text not null,
    tire_compound text not null,
    used_tire boolean,
    lap_count integer check (lap_count is null or lap_count >= 0),
    avg_pace_seconds numeric(10, 3) check (
        avg_pace_seconds is null or avg_pace_seconds > 0
    ),
    std_pace_seconds numeric(10, 3) check (
        std_pace_seconds is null or std_pace_seconds >= 0
    ),
    degradation_rate numeric(12, 6),
    primary key (race_id, driver_id, session_type, tire_compound)
);

-- stores derived predictors that are not represented directly by the normalized
-- facts above. keep target/outcome columns in race_result, not in feature_values.
create table if not exists driver_race_feature_snapshot (
    race_id text not null references race (race_id),
    driver_id text not null references driver (driver_id),
    constructor_id text references constructor (constructor_id),
    prediction_stage text not null check (
        prediction_stage in ('pre_qual', 'pre_race')
    ),
    source_dataset text not null,
    feature_values jsonb not null check (
        jsonb_typeof(feature_values) = 'object'
    ),
    loaded_at timestamptz not null default current_timestamp,
    primary key (race_id, driver_id, prediction_stage)
);

create index if not exists ix_race_season_round
    on race (season_year, round);
create index if not exists ix_race_result_driver
    on race_result (driver_id, race_id);
create index if not exists ix_race_result_constructor
    on race_result (constructor_id, race_id);
create index if not exists ix_practice_driver_session
    on practice_result (driver_id, session_type, race_id);
create index if not exists ix_pit_stop_driver_race
    on pit_stop (driver_id, race_id);
create index if not exists ix_feature_snapshot_stage
    on driver_race_feature_snapshot (prediction_stage, race_id);
create index if not exists ix_feature_values_gin
    on driver_race_feature_snapshot using gin (feature_values);
